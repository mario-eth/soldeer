//! Lockfile handling.
//!
//! The lockfile contains the resolved dependencies of a project. It is a TOML file with an array of
//! dependencies, each containing the name, version, and other information about the dependency.
//!
//! The lockfile is used to ensure that the same versions of dependencies are installed across
//! different machines. It is also used to skip the installation of dependencies that are already
//! installed.
use crate::{
    config::Dependency,
    errors::LockError,
    utils::{is_symlink, sanitize_filename},
};
use log::{debug, warn};
use serde::{Deserialize, Serialize};
use std::{
    fs,
    path::{Path, PathBuf},
};
use uuid::Uuid;

pub mod forge;

pub const SOLDEER_LOCK: &str = "soldeer.lock";

pub type Result<T> = std::result::Result<T, LockError>;

/// A trait implemented by lockfile entries to provide the install path
pub trait Integrity {
    /// Returns the install path of the dependency.
    fn install_path(&self, deps: impl AsRef<Path>) -> PathBuf;

    /// Returns the integrity checksum if relevant.
    fn integrity(&self) -> Option<&String>;
}

/// The version of the `soldeer.lock` file format.
///
/// The version is stored in the `version` key at the root of the lockfile. Lockfiles which do not
/// have that key were generated by Soldeer 0.11 or older.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, derive_more::TryFrom)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[try_from(repr)]
#[repr(u64)]
pub enum LockFileVersion {
    /// Lockfiles generated by Soldeer 0.11 and older.
    ///
    /// The unzipping behaved slightly differently in those versions, such that the integrity
    /// checksum does not match the output produced by later Soldeer versions.
    V1 = 1,

    /// The current format, almost identical to V1, except it has versioning and the integrity
    /// checksums are not compatible with the older version.
    #[default]
    V2 = 2,
}

impl From<LockFileVersion> for u64 {
    /// The number to store in the lockfile.
    fn from(value: LockFileVersion) -> Self {
        value as Self
    }
}

impl LockFileVersion {
    /// Whether the lockfile predates the archive extraction change of Soldeer 0.12.
    ///
    /// For such lockfiles, a failed integrity check of an HTTP dependency is expected, because the
    /// checksum was computed from a different on-disk layout.
    pub fn is_legacy(self) -> bool {
        self == Self::V1
    }
}

/// A lock entry for a git dependency.
#[derive(Debug, Clone, PartialEq, Eq, Hash, bon::Builder)]
#[builder(on(String, into))]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
#[non_exhaustive]
pub struct GitLockEntry {
    /// The name of the dependency.
    pub name: String,

    /// The version (this corresponds to the version requirement of the dependency).
    pub version: String,

    /// The git url of the dependency.
    pub git: String,

    /// The resolved git commit hash.
    pub rev: String,
}

impl Integrity for GitLockEntry {
    /// Returns the install path of the dependency.
    ///
    /// The directory does not need to exist. Since the lock entry contains the version,
    /// the install path can be calculated without needing to check the actual directory.
    fn install_path(&self, deps: impl AsRef<Path>) -> PathBuf {
        format_install_path(&self.name, &self.version, deps)
    }

    /// There is no integrity checksum for git lock entries
    fn integrity(&self) -> Option<&String> {
        None
    }
}

/// A lock entry for an HTTP dependency.
