    #[test]
    fn test_read_lockfile_version() {
        let dir = testdir!();
        let file_path = dir.join(SOLDEER_LOCK);
        let content = r#"[[dependencies]]
name = "test"
version = "1.0.0"
git = "git@github.com:test/test.git"
rev = "123456"
"#;
        // a lockfile without a version key was generated by soldeer v0.11 or older
        fs::write(&file_path, content).unwrap();
        assert_eq!(read_lockfile(&file_path).unwrap().version, LockFileVersion::V1);

        fs::write(
            &file_path,
            format!(
                "version = 1

{content}"
            ),
        )
        .unwrap();
        assert_eq!(read_lockfile(&file_path).unwrap().version, LockFileVersion::V1);

        fs::write(
            &file_path,
            format!(
                "version = 2

{content}"
            ),
        )
        .unwrap();
        let lockfile = read_lockfile(&file_path).unwrap();
        assert_eq!(lockfile.version, LockFileVersion::V2);
        assert_eq!(lockfile.unknown_version, None);

        // a version we don't know about is read as the most recent known format, and reported so
        // that the user can be told to upgrade
        fs::write(
            &file_path,
            format!(
                "version = 3

{content}"
            ),
        )
        .unwrap();
        let lockfile = read_lockfile(&file_path).unwrap();
        assert_eq!(lockfile.version, LockFileVersion::V2);
        assert_eq!(lockfile.unknown_version, Some(3));
    }

