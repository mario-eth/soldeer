    #[test]
    fn test_only_integrity_differs() {
        let http = |version: &str, checksum: &str, integrity: &str| -> LockEntry {
            HttpLockEntry::builder()
                .name("test")
                .version(version)
                .url("https://example.com/zip.zip")
                .checksum(checksum)
                .integrity(integrity)
                .build()
                .into()
        };
        let git: LockEntry = GitLockEntry::builder()
            .name("test2")
            .version("1.0.0")
            .git("git@github.com:test/test.git")
            .rev("123456")
            .build()
            .into();
        let old = [http("1.0.0", "123456", "beef"), git.clone()];

        // same entries, in a different order
        assert!(only_integrity_differs(&old, &[git.clone(), http("1.0.0", "123456", "beef")]));
        // only the integrity checksum changed
        assert!(only_integrity_differs(&old, &[http("1.0.0", "123456", "dead"), git.clone()]));
        // the archive checksum changed
        assert!(!only_integrity_differs(&old, &[http("1.0.0", "abcdef", "beef"), git.clone()]));
        // the version changed
        assert!(!only_integrity_differs(&old, &[http("1.1.0", "123456", "beef"), git.clone()]));
        // a dependency was removed
        assert!(!only_integrity_differs(&old, &[git]));
    }

